package com.bloodline.android.runtime.audio

import com.bloodline.android.runtime.backends.AudioBridge
import com.bloodline.android.runtime.graphics.RegistrySetting
import java.io.File

/**
 * How Windows audio reaches the phone's speakers.
 *
 * The chain, because the number of hops is the reason this needs explaining:
 *
 * ```
 * Bloodlines ──▶ DirectSound3D ──▶ Wine's ALSA driver ──▶ our ALSA plugin ──▶ Android
 *   (x86)          (in the prefix)        (in the prefix)      (host)          (host)
 * ```
 *
 * The last hop is the only one this app owns. It is done the way ALSA intends:
 * a `pcm` definition in a config file naming a plugin, pointed at by
 * `ALSA_CONFIG_PATH` and `ALSA_PLUGIN_DIR`. Those two variables are exactly
 * what the working Android runtimes set, which is why they are used here
 * rather than invented ones.
 *
 * Inside the prefix, Wine is told to use its ALSA driver through the registry.
 *
 * **The plugin is looked for, never assumed.** [RuntimeLayout] searches the
 * installed packages for [PLUGIN_LIBRARY] on every launch and passes what it
 * finds as [plugin]. When it finds nothing — which, until that library exists,
 * is always — the config written below names ALSA's own `null` device instead.
 * That fallback is the point of the field: naming a PCM type nothing
 * implements is not a graceful degradation, it is an "Unknown PCM" failure the
 * moment Wine opens the device.
 */
data class AudioConfiguration(
    val bridge: AudioBridge,
    val plugin: File? = null,
    val sampleRateHz: Int = DEFAULT_SAMPLE_RATE,
    val bufferFrames: Int = DEFAULT_BUFFER_FRAMES,
    val channels: Int = DEFAULT_CHANNELS,
) {

    /** True when the user asked for sound, which is not the same as getting it. */
    val producesSound: Boolean get() = bridge.producesSound

    /**
     * True when the hop to Android actually exists.
     *
     * When this is false the guest still gets a working ALSA device — it just
     * leads nowhere. Keeping the two answers separate is what lets a
     * diagnostics report say "sound is enabled but nothing is carrying it"
     * rather than either lying or staying silent.
     */
    val routedToAndroid: Boolean get() = plugin != null

    /**
     * The ALSA config file, written into the runtime directory.
     *
     * `pcm.!default` overrides the device name every ALSA client asks for by
     * default, so no per-application configuration is needed.
     *
     * Two forms, and [plugin] picks between them. With a plugin library
     * present, "default" routes through it. Without one, "default" is ALSA's
     * `null` device, which always exists: it opens, it accepts every sample
     * the game writes, and it emits silence. The game sees a sound card that
     * works; the rest of the runtime can be exercised through it. Naming a
     * plugin that is not there would instead fail at open and take the audio
     * device down with it.
     */
    fun asoundConf(): String = buildString {
        appendLine("# Generated by Bloodlines Android. Do not edit: it is rewritten on")
        appendLine("# every launch from the settings in the launcher.")
        appendLine()

        val pluginLibrary = plugin
        if (pluginLibrary != null) {
            appendLine("# Wine's ALSA driver inside the prefix opens \"default\"; this routes")
            appendLine("# it to the plugin implemented by ${pluginLibrary.name}.")
            appendLine("pcm.!default {")
            appendLine("    type $PLUGIN_NAME")
            appendLine("    bridge \"${bridge.id}\"")
            appendLine("    rate $sampleRateHz")
            appendLine("    buffer $bufferFrames")
            appendLine("    channels $channels")
            appendLine("}")
            appendLine()
            appendLine("ctl.!default {")
            appendLine("    type $PLUGIN_NAME")
            appendLine("}")
        } else {
            appendLine("# No PCM plugin was found in the runtime, so \"default\" is ALSA's own")
            appendLine("# null device rather than a plugin name that would fail to resolve.")
            appendLine("# The game gets a sound card that opens and stays silent; the rest of")
            appendLine("# the runtime is unaffected and can still be exercised.")
            appendLine("pcm.!default {")
            appendLine("    type null")
            appendLine("}")
            appendLine()
            appendLine("ctl.!default {")
            appendLine("    type null")
            appendLine("}")
        }
    }

    /** Writes [asoundConf] into [runtimeDir] and returns its path. */
    fun writeAsoundConf(runtimeDir: File): File {
        val directory = File(runtimeDir, "etc/alsa")
        directory.mkdirs()
        val file = File(directory, "asound.conf")
        file.writeText(asoundConf())
        return file
    }

    /** The environment variables the guest needs. */
    fun environment(runtimeDir: File): Map<String, String> = linkedMapOf(
        // Both are real ALSA variables. ALSA_CONFIG_PATH names the file above;
        // ALSA_PLUGIN_DIR is where the plugin library is looked for, so it
        // points at whatever directory actually holds it.
        "ALSA_CONFIG_PATH" to writeAsoundConf(runtimeDir).absolutePath,
        "ALSA_PLUGIN_DIR" to (plugin?.parentFile ?: File(runtimeDir, "lib/alsa-lib")).absolutePath,
    )

    /** The registry settings the prefix needs. */
    fun registrySettings(): List<RegistrySetting> = buildList {
        add(
            if (producesSound) {
                RegistrySetting.audioDriver("winealsa.drv")
            } else {
                // "No audio" is a real and useful setting: it starts the game
                // muted so that a sound-server problem cannot stop the rest of
                // the runtime from being tested.
                RegistrySetting.audioDriver("")
            },
        )
    }

    /**
     * One line for the report.
     *
     * It says when the bridge is configured but nothing is carrying it,
     * because "sound is on" and "sound is reaching the speakers" are different
     * claims and only one of them can be made here.
     */
    fun summary(): String = buildString {
        append(bridge.title)
        if (!producesSound) {
            append(" · muted")
        } else if (!routedToAndroid) {
            append(" · enabled, but no PCM plugin is present, so the game will be silent")
        } else {
            append(" · ").append(sampleRateHz).append(" Hz · ")
                .append(bufferFrames).append(" frames")
        }
    }

    companion object {

        /**
         * 48 kHz because it is what Android's audio HALs are built around, and
         * resampling a game that expects 44.1 kHz is cheaper than fighting the
         * device's native rate.
         */
        const val DEFAULT_SAMPLE_RATE = 48_000

        /**
         * 512 frames at 48 kHz is about 11 ms. Large enough to avoid dropouts
         * on a mid-range device, small enough that dialogue does not visibly
         * lag the animation.
         */
        const val DEFAULT_BUFFER_FRAMES = 512

        const val DEFAULT_CHANNELS = 2

        /** The ALSA PCM type this app asks for. */
        const val PLUGIN_NAME = "bloodline"

        /**
         * The library that implements [PLUGIN_NAME].
         *
         * Searched for at launch, not assumed to be there.
         */
        const val PLUGIN_LIBRARY = "libpcm_bloodline.so"
    }
}
